import { readFile, writeFile } from 'node:fs/promises';
import Ajv from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import {build} from 'esbuild';
const ajv = new Ajv({strict:true, code:{source:true,esm:true}, inlineRefs:false});
for (const name of ['numerical-ir-v1','native-evidence-v1','optimization-report-v1'])
  ajv.addSchema(JSON.parse(await readFile(`docs/schemas/deepbom-${name}.schema.json`,'utf8')));
const generated=standalone(ajv, ajv.getSchema('https://deepbom.org/schemas/deepbom-optimization-report-v1.schema.json'));
const bundled=await build({stdin:{contents:generated,resolveDir:process.cwd()},bundle:true,platform:'browser',format:'esm',minify:true,write:false,metafile:true});
const code = '// Generated by scripts/generate-optimization-report-validator.mjs; do not edit.\n' + bundled.outputFiles[0].text;
// Standalone browser validation must not acquire runtime npm dependencies.
if (Object.values(bundled.metafile.outputs).some(o=>o.imports.length)) throw Error('Generated report validator contains a runtime dependency');
const file='web/lib/optimization-report-validator.js';
if(process.argv.includes('--check')) {
  if(await readFile(file,'utf8')!==code)throw Error('Stale optimization report validator');
} else await writeFile(file,code);
console.log(`Optimization report validator: ${Buffer.byteLength(code)} bytes`);
