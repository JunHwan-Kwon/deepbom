import assert from "node:assert/strict";

import {
  analyzeCoreMlProgramCorpusArtifact,
  readCoreMlProgramCorpus,
  receiptMatchesBaseline,
  validateCoreMlProgramCorpus,
} from "./coreml-mlprogram-corpus-lib.mjs";

const manifest = await readCoreMlProgramCorpus();
validateCoreMlProgramCorpus(manifest, { requireBaselines: true });
const receipts = [];
for (const artifact of manifest.artifacts) {
  const receipt = await analyzeCoreMlProgramCorpusArtifact(artifact);
  assert(receiptMatchesBaseline(receipt, artifact), `${artifact.id}: generated bytes or analysis receipt changed`);
  receipts.push(receipt);
}
const staticFixture = receipts.find((row) => row.contract_class === "static_external_blob");
assert.equal(staticFixture.total_macs, 72);
assert.equal(staticFixture.weight_integrity_status, "assessed");
assert.equal(staticFixture.weight_payload_bytes, 72);
assert.equal(staticFixture.byte_conservation, true);
const enumerated = receipts.find((row) => row.contract_class === "enumerated_shape");
assert.equal(enumerated.input_flexibility.kind, "enumerated");
assert.deepEqual(enumerated.input_flexibility.shapes, [[1, 3, 224, 224], [1, 3, 256, 256]]);
assert(enumerated.unknown_mil_dimension_count > 0, "Enumerated-shape fixture lost its variable MIL dimensions");
const ranged = receipts.find((row) => row.contract_class === "bounded_shape_range");
assert.equal(ranged.input_flexibility.kind, "range");
assert.deepEqual(ranged.input_flexibility.dimensions.map((row) => [row.lower_bound, row.upper_bound]), [[1, 1], [3, 3], [128, 512], [128, 512]]);
assert(ranged.unknown_mil_dimension_count > 0, "Range fixture lost its variable MIL dimensions");
const blockwise = receipts.find((row) => row.contract_class === "blockwise_affine_compression");
assert.equal(blockwise.compression_contract_status, "assessed_exact_serialized_contracts");
assert.equal(blockwise.compression_transform_count, 1);
assert.equal(blockwise.compression_exact_contract_count, 1);
assert.equal(blockwise.weight_payload_bytes, 16);
assert.equal(blockwise.byte_conservation, true);
const lut = receipts.find((row) => row.contract_class === "lut_palettization_compression");
assert.equal(lut.compression_contract_status, "assessed_exact_serialized_contracts");
assert.equal(lut.compression_transform_count, 1);
assert.equal(lut.compression_exact_contract_count, 1);
assert.equal(manifest.artifacts.every((row) => row.ecosystem_prevalence_claim === false), true);
console.log("Five source-pinned Core ML MLProgram packages reproduce blob, flexible-shape, blockwise affine, and LUT contracts.");
