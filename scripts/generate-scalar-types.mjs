import { readFileSync, writeFileSync } from "node:fs";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";

const source = readFileSync(new URL("../config/scalar-types.v1.json", import.meta.url), "utf8");
const registry = JSON.parse(source);
assert.equal(registry.schema, "deepbom.scalar_types.v1");
const names = new Set(), entries = [];
for (const type of registry.types) {
  assert.ok(Number.isSafeInteger(type.bits) && type.bits > 0 && type.bits <= 128);
  assert.ok(["integer", "float", "complex", "boolean"].includes(type.kind));
  assert.equal(typeof type.signed, "boolean");
  for (const name of [type.name, ...type.aliases]) {
    assert.match(name, /^[A-Z][A-Z0-9_]*$/);
    assert.ok(!names.has(name), `Duplicate scalar dtype ${name}`);
    names.add(name);
    entries.push([name, { bits: type.bits, kind: type.kind, signed: type.signed }]);
  }
}
entries.sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
const hash = createHash("sha256").update(source).digest("hex");
const header = `// Generated by scripts/generate-scalar-types.mjs; do not edit.\n// Source: config/scalar-types.v1.json (sha256:${hash})\n`;
const js = header + "export const SCALAR_TYPES = Object.freeze(Object.assign(Object.create(null), {\n"
  + entries.map(([name, value]) => `  ${JSON.stringify(name)}: Object.freeze(${JSON.stringify(value)}),`).join("\n") + "\n}));\n";
const rs = header + "pub(crate) fn scalar_dtype_bits(dtype: &str) -> Option<u32> {\n    match dtype {\n"
  + registry.types.map(type => `        ${[type.name, ...type.aliases].map(name => JSON.stringify(name)).join(" | ")} => Some(${type.bits}),`).join("\n")
  + "\n        _ => None,\n    }\n}\n";
for (const [file, body] of [["web/lib/scalar-types.generated.js", js], ["src/scalar_types_generated.rs", rs]]) {
  const path = new URL(`../${file}`, import.meta.url);
  if (process.argv.includes("--check")) assert.equal(readFileSync(path, "utf8"), body, `Stale generated scalar rules: ${file}`);
  else writeFileSync(path, body);
}
console.log(`Scalar rules: ${registry.types.length} encodings, ${names.size} names; JavaScript/Rust ${process.argv.includes("--check") ? "verified" : "generated"}.`);
