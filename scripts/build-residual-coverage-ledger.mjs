function coreMlPublicPopulationSummary(filename) {
  const bytes = readFileSync(filename);
  const evidence = JSON.parse(bytes.toString("utf8"));
  if (evidence.schema !== "deepbom.cyclonedx_generalization_evidence.v1") {
    throw new Error(`Unexpected Core ML public-population source schema: ${evidence.schema || "missing"}.`);
  }
  const population = evidence.format_populations?.coreml;
  if (!population || !Number.isSafeInteger(population.unique_artifact_count) || population.unique_artifact_count <= 0) {
    throw new Error("Core ML public-population evidence is missing a positive unique-artifact denominator.");
  }
  const artifactCount = population.unique_artifact_count;
  for (const key of [
    "architecture_strata",
    "task_strata",
    "precision_strata",
    "graph_presence",
    "quantization_classification",
    "serialized_contract_status",
  ]) {
    const total = Object.values(population[key] || {}).reduce((sum, count) => sum + Number(count || 0), 0);
    if (total !== artifactCount) throw new Error(`Core ML ${key} does not conserve the ${artifactCount}-artifact denominator.`);
  }
  if (population.external_parameter_count !== population.affine_external_parameter_count
    + population.unquantized_or_undeclared_external_parameter_count) {
    throw new Error("Core ML external-parameter quantization states do not conserve their denominator.");
  }
  return {
    evidence_class: "HASH_IDENTIFIED_PUBLIC_ARTIFACT_POPULATION",
    source_path: filename.replaceAll("\\", "/"),
    source_schema: evidence.schema,
    source_sha256: sha256(bytes),
    artifact_count: artifactCount,
    path_record_count: population.path_record_count,
    catalog_source_count: population.repository_or_catalog_source_count,
    architecture_strata: population.architecture_strata,
    task_strata: population.task_strata,
    precision_strata: population.precision_strata,
    serialized_graph_present_count: population.graph_presence.serialized_graph_present || 0,
    serialized_graph_payload_not_decoded_count: population.graph_presence.serialized_graph_payload_not_decoded || 0,
    quantization_classification: population.quantization_classification,
    serialized_contract_status: population.serialized_contract_status,
    serialized_contract_issue_codes: population.serialized_contract_issue_codes,
    external_parameter_count: population.external_parameter_count,
    affine_external_parameter_count: population.affine_external_parameter_count,
    singleton_model_quantization_lossy_count: population.singleton_model_quantization_lossy_count,
    singleton_model_quantization_applicable_count: population.singleton_model_quantization_applicable_count,
    ecosystem_prevalence_claim: false,
    device_placement_claim: false,
    non_claim: "This bounded public cohort comes from one catalog source. It does not estimate Core ML ecosystem prevalence, parser-wide coverage, compiled-plan device usage, or executed placement.",
  };
}

function rankPriorities(rows) {
  return rows.filter((row) => row.class !== "observed_analyzer_residual" || row.affected_entities > 0).sort((left, right) => {
    const classRank = (row) => row.class === "observed_artifact_defect" ? 2 : row.class === "observed_analyzer_residual" ? 1 : 0;
    return classRank(right) - classRank(left)
      || right.affected_artifacts - left.affected_artifacts
      || right.affected_entities - left.affected_entities
      || right.deterministic_closability - left.deterministic_closability
      || right.deployment_impact - left.deployment_impact
      || left.id.localeCompare(right.id);
  }).map((row, index) => ({ rank: index + 1, ...row }));
}

function mergeHistograms(rows, key, normalize = (value) => value) {
  const counts = new Map();
  for (const row of rows) for (const item of row.coverage_residuals?.[key] || []) {
    const name = normalize(String(item.name || "unknown_reason"));
    counts.set(name, (counts.get(name) || 0) + Number(item.count || 0));
  }
  return [...counts.entries()].sort((left, right) => right[1] - left[1] || left[0].localeCompare(right[0])).map(([name, count]) => ({ name, count }));
}

function normalizeResidualReason(reason) {
  if (reason.startsWith("blocked_by_upstream_contract_conflict:")) return "blocked_by_upstream_contract_conflict";
  return reason.replace(
    / nominal MACs are blocked by invalid tensor contract .*; no stale declared shape is used\.$/,
    " nominal MACs are blocked by invalid tensor contract; no stale declared shape is used.",
  );
}

function normalizeOpResidualReason(value) {
  const separator = value.indexOf(":");
  return separator < 0
    ? normalizeResidualReason(value)
    : `${value.slice(0, separator)}:${normalizeResidualReason(value.slice(separator + 1))}`;
}

function countStrings(values) {
  const counts = new Map();
  for (const value of values) counts.set(value, (counts.get(value) || 0) + 1);
  return Object.fromEntries([...counts].sort(([left], [right]) => left.localeCompare(right)));
}

function sha256(bytes) { return createHash("sha256").update(bytes).digest("hex"); }

function readSweepDocument(filename) {
  const bytes = readFileSync(filename);
  return JSON.parse((filename.endsWith(".gz") ? gunzipSync(bytes) : bytes).toString("utf8"));
}

function parseArgs(argv) {
  const output = { sweeps: [], output: "corpus/residual-coverage-priorities.v1.json" };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === "--sweep") output.sweeps.push(argv[++index]);
    else if (argv[index] === "--output") output.output = argv[++index];
    else throw new Error(`Unknown argument: ${argv[index]}`);
  }
  return output;
}
