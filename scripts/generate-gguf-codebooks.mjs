import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE = Object.freeze({
  repository: "ggml-org/llama.cpp",
  commit: "7bd8282c37fcd9c4d7236106d664761a23318f18",
  path: "ggml/src/ggml-common.h",
  sha256: "af255601767325f087313fa84b9435cb77aeec37df6b61b98d9ecc65f29fb4a0",
});

const SPECS = Object.freeze({
  ksigns_iq2xs: Object.freeze({ entries: 128, width: 1 }),
  iq2xxs_grid: Object.freeze({ entries: 256, width: 8 }),
  iq2xs_grid: Object.freeze({ entries: 512, width: 8 }),
  iq2s_grid: Object.freeze({ entries: 1024, width: 8 }),
  iq3xxs_grid: Object.freeze({ entries: 256, width: 4 }),
  iq3s_grid: Object.freeze({ entries: 512, width: 4 }),
  iq1s_grid: Object.freeze({ entries: 2048, width: 8 }),
});

const outputPath = fileURLToPath(new URL("../web/lib/gguf-codebooks.generated.js", import.meta.url));
const sourceUrl = `https://raw.githubusercontent.com/${SOURCE.repository}/${SOURCE.commit}/${SOURCE.path}`;
const response = await fetch(sourceUrl);
if (!response.ok) throw new Error(`GGUF codebook source returned HTTP ${response.status}`);
const sourceBytes = Buffer.from(await response.arrayBuffer());
const sourceDigest = createHash("sha256").update(sourceBytes).digest("hex");
if (sourceDigest !== SOURCE.sha256) throw new Error(`GGUF codebook source digest mismatch: ${sourceDigest}`);
const sourceText = sourceBytes.toString("utf8");

function extractTable(name, spec) {
  const pattern = new RegExp(`GGML_TABLE_BEGIN\\([^,]+,\\s*${name},[^\\n]*\\)\\s*([\\s\\S]*?)GGML_TABLE_END\\(\\)`);
  const match = sourceText.match(pattern);
  if (!match) throw new Error(`GGUF codebook source is missing ${name}`);
  const tokens = match[1].replace(/\/\/.*$/gm, "").match(/0x[0-9a-fA-F]+|\b\d+\b/g) || [];
  if (tokens.length !== spec.entries) throw new Error(`${name} contains ${tokens.length} entries; expected ${spec.entries}`);
  const bytes = Buffer.alloc(spec.entries * spec.width);
  tokens.forEach((token, index) => {
    let value = BigInt(token);
    for (let offset = 0; offset < spec.width; offset += 1) {
      bytes[index * spec.width + offset] = Number(value & 255n);
      value >>= 8n;
    }
    if (value !== 0n) throw new Error(`${name} entry ${index} exceeds ${spec.width} byte(s)`);
  });
  return Object.freeze({
    entries: spec.entries,
    width: spec.width,
    byte_length: bytes.length,
    sha256: createHash("sha256").update(bytes).digest("hex"),
    base64: bytes.toString("base64"),
  });
}

function quotedChunks(value) {
  const chunks = value.match(/.{1,100}/g) || [""];
  return chunks.map((chunk) => `    "${chunk}"`).join(" +\n");
}

const tables = Object.fromEntries(Object.entries(SPECS).map(([name, spec]) => [name, extractTable(name, spec)]));
const rows = Object.entries(tables).map(([name, table]) => `  ${name}: Object.freeze({
    entries: ${table.entries}, width: ${table.width}, byte_length: ${table.byte_length},
    sha256: "${table.sha256}",
    base64: ${quotedChunks(table.base64)},
  }),`).join("\n");

const generated = `// Generated by scripts/generate-gguf-codebooks.mjs from a content-verified pinned source.\n`
  + `// Do not edit this file by hand.\n\n`
  + `export const GGUF_CODEBOOK_SOURCE = Object.freeze(${JSON.stringify(SOURCE, null, 2)});\n\n`
  + `const ENCODED = Object.freeze({\n${rows}\n});\n\n`
  + `const TABLES = new Map();\n\n`
  + `function table(name) {\n`
  + `  const encoded = ENCODED[name];\n`
  + `  if (!encoded) throw new Error(\`unknown GGUF codebook \${name}\`);\n`
  + `  if (!TABLES.has(name)) {\n`
  + `    const binary = atob(encoded.base64);\n`
  + `    const bytes = Uint8Array.from(binary, (value) => value.charCodeAt(0));\n`
  + `    if (bytes.length !== encoded.byte_length) throw new Error(\`GGUF codebook \${name} byte length is invalid\`);\n`
  + `    TABLES.set(name, bytes);\n`
  + `  }\n`
  + `  return TABLES.get(name);\n`
  + `}\n\n`
  + `export function ggufCodebookEntry(name, index) {\n`
  + `  const encoded = ENCODED[name];\n`
  + `  if (!encoded || !Number.isSafeInteger(index) || index < 0 || index >= encoded.entries) throw new Error(\`GGUF codebook \${name} index \${index} is invalid\`);\n`
  + `  const start = index * encoded.width;\n`
  + `  return table(name).subarray(start, start + encoded.width);\n`
  + `}\n\n`
  + `export function ggufCodebookByte(name, index) {\n`
  + `  const encoded = ENCODED[name];\n`
  + `  if (!encoded || encoded.width !== 1 || !Number.isSafeInteger(index) || index < 0 || index >= encoded.entries) throw new Error(\`GGUF byte codebook \${name} index \${index} is invalid\`);\n`
  + `  return table(name)[index];\n`
  + `}\n\n`
  + `export function ggufCodebookManifest() {\n`
  + `  return Object.freeze(Object.fromEntries(Object.entries(ENCODED).map(([name, row]) => [name, Object.freeze({ entries: row.entries, width: row.width, byte_length: row.byte_length, sha256: row.sha256 })])));\n`
  + `}\n\n`
  + `export function ggufCodebookBytesForVerification(name) { return table(name).slice(); }\n`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== generated) throw new Error("Generated GGUF codebooks are stale; run npm run generate:gguf-codebooks");
  console.log(`GGUF codebooks match ${SOURCE.repository}@${SOURCE.commit}/${SOURCE.path}.`);
} else {
  writeFileSync(outputPath, generated, "utf8");
  console.log(`Generated ${Object.keys(tables).length} GGUF codebooks at ${outputPath}.`);
}
