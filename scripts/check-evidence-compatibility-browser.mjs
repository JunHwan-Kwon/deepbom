import assert from "node:assert/strict";
import { readFile, mkdir } from "node:fs/promises";
import { createServer } from "node:http";
import path from "node:path";
import { chromium } from "playwright";
import { launchChromium } from "./browser-launch.mjs";
const built = process.argv.includes("--dist"), root = process.cwd();
const catalogIndex = JSON.parse(await readFile("docs/evidence-ir/compatibility/index.json", "utf8"));
const version = catalogIndex.current;
const catalog = JSON.parse(await readFile(`docs/evidence-ir/compatibility/${version}.json`, "utf8"));
const server = createServer(async (req, res) => {
  try {
    let pathname = new URL(req.url, "http://localhost").pathname;
    if (pathname.endsWith("/")) pathname += "index.html";
    const relative = built ? `dist${pathname}` : pathname.startsWith("/schemas/compatibility/") ? `docs/evidence-ir/compatibility/${pathname.split("/").pop()}` : pathname.startsWith("/schemas/") ? `docs${pathname}` : `web${pathname}`;
    const file = path.resolve(root, relative); if (!file.startsWith(root + path.sep)) throw Error("invalid path");
    res.setHeader("content-type", ({ ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".json": "application/json" })[path.extname(file)] || "application/octet-stream");
    res.end(await readFile(file));
  } catch { res.writeHead(404); res.end(); }
});
await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
const origin = `http://127.0.0.1:${server.address().port}`, url = `${origin}/guides/evidence-ir/compatibility/`;
let browser;
try {
  browser = await launchChromium(chromium);
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } }), errors = [], external = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (!request.url().startsWith(origin)) external.push(request.url()); });
  const ready = async () => { await page.waitForFunction(() => document.querySelector("#revision").textContent.includes("snapshot verified")); };
  await page.goto(url); await ready();
  assert.equal(await page.locator(".mapping-row").count(), catalog.mappings.length);
  assert.match(await page.locator("#mapping-detail").textContent(), /ONNX → Artifact IR/);
  await page.getByRole("navigation", { name: "Connected mappings" }).getByRole("button", { name: "Artifact IR → Model IR", exact: true }).click();
  assert.match(await page.locator("#mapping-detail h3").textContent(), /Artifact IR → Model IR/);
  await page.getByRole("navigation", { name: "Connected mappings" }).getByRole("button", { name: "Model IR → Model summary", exact: true }).click();
  assert.match(await page.locator("#mapping-detail h3").textContent(), /Model IR → Model summary/);
  assert.equal(await page.locator("#inputs article").count(), catalog.nodes.filter(n => n.kind === "input").length);
  assert.equal(await page.locator("#outputs article").count(), catalog.nodes.filter(n => n.kind === "output").length);
  await page.locator("#query").fill("OMOP");
  await page.locator('[data-mapping="omop-provenance"]').click();
  assert.match(await page.locator("#mapping-detail").textContent(), /CDM_SOURCE/);
  await page.locator("#reset").click();
  await page.locator("#layer").selectOption("provenance");
  await page.locator("#direction").selectOption("output");
  await page.locator("#mapping-status").selectOption("proposed");
  assert.equal(await page.locator(".mapping-row").count(), 1);
  assert.match(await page.locator("#mapping-detail").textContent(), /No field mapping is implemented/);
  await page.locator("#reset").click();
  await page.locator("#query").fill("SPDX-2.3");
  assert.equal(await page.locator(".mapping-row").count(), catalog.mappings.filter(row=>row.to==='output-spdx').length);
  await page.locator('[data-mapping="envelope-spdx"]').focus(); await page.keyboard.press("Enter");
  assert.match(await page.locator("#mapping-detail").textContent(), /NOASSERTION/);
  await page.locator('[data-mapping="workflow-spdx-projection"]').click();
  assert.match(await page.locator("#mapping-detail").textContent(), /loss ledger|source JSON/);
  await page.locator("#query").fill("__absent__ <img src=x onerror=alert(1)>");
  assert.equal(await page.locator(".mapping-row").count(), 0);
  assert(await page.locator("#empty").isVisible()); assert.equal(await page.locator("img").count(), 0);
  await page.goto(`${url}?version=${version}&mapping=provenance-cyclonedx`); await ready();
  assert.match(await page.locator("#mapping-detail").textContent(), /deepbom:provenance:fieldLedger/);
  const downloadPromise = page.waitForEvent("download"); await page.locator("#download-catalog").click();
  assert.deepEqual(JSON.parse(await readFile(await (await downloadPromise).path(), "utf8")), catalog);
  await mkdir(".local-validation/compatibility", { recursive: true });
  await page.screenshot({ path: ".local-validation/compatibility/desktop.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "mobile page must not overflow");
  await page.screenshot({ path: ".local-validation/compatibility/mobile.png", fullPage: true });
  await page.goto(`${url}?version=999.0.0`); await page.locator("#load-error").waitFor({ state: "visible" });
  assert.equal(await page.locator(".mapping-row").count(), 0);
  await page.route(`**/schemas/compatibility/${version}.json`, route => route.fulfill({ contentType: "application/json", body: JSON.stringify({ ...catalog, status: "forged" }) }));
  await page.goto(url); await page.locator("#load-error").waitFor({ state: "visible" });
  assert.match(await page.locator("#load-error").textContent(), /checksum mismatch/);
  assert.equal(await page.locator(".mapping-row").count(), 0);
  await page.unroute(`**/schemas/compatibility/${version}.json`);
  await page.locator("#version").selectOption(version); await ready();
  assert.equal(await page.locator(".mapping-row").count(), catalog.mappings.length);
  assert.deepEqual(errors, []); assert.deepEqual(external, [], "catalog must not require third-party requests");
  console.log(`Compatibility browser${built ? " (dist)" : ""}: search, combined filters, keyboard selection, version/deep links, download parity, mobile layout, unknown versions and corrupted snapshot rejection passed.`);
} finally { await browser?.close(); await new Promise(resolve => server.close(resolve)); }
