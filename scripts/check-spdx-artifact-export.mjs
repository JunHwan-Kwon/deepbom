import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { analyzeOnnxModel } from "../web/onnx.js";
import { buildArtifactEvidenceEnvelope } from "../web/lib/artifact-evidence-envelope.js";
import { buildSpdxArtifactDocument } from "../web/lib/spdx-artifact-export.js";
import { canonicalJson } from "../web/lib/report-utils.js";
import { assertSpdx23 } from "./spdx-23-schema.mjs";

const bytes = await readFile("web/samples/mnist-8.onnx");
const hash = createHash("sha256").update(bytes).digest("hex");
const analysis = analyzeOnnxModel(bytes, "mnist-8.onnx");
const envelope = buildArtifactEvidenceEnvelope(analysis, { hash, fileSizeBytes: bytes.length });
const options = { generatedAt: "2026-09-16T00:00:00Z" };
const document = buildSpdxArtifactDocument(envelope, options);
assertSpdx23(document);
assert.deepEqual(document, buildSpdxArtifactDocument(envelope, options));
assert.equal(document.packages[0].packageFileName, "mnist-8.onnx");
assert.equal(document.packages[0].primaryPackagePurpose, "FILE");
assert.equal(document.packages[0].filesAnalyzed, false);
assert.deepEqual(document.packages[0].checksums, [{ algorithm: "SHA256", checksumValue: hash }]);
assert.equal(document.packages[0].licenseDeclared, "NOASSERTION");
assert.equal(document.packages[0].licenseConcluded, "NOASSERTION");
assert.equal(document.packages[0].copyrightText, "NOASSERTION");
assert.equal(document.files, undefined, "Do not emit incomplete SPDX File records without SHA-1");
assert.deepEqual(document.relationships, []);
const annotation = JSON.parse(document.annotations[0].comment);
assert.equal(annotation.evidence_envelope_sha256, envelope.envelope_sha256);
assert.deepEqual(annotation.findings, envelope.findings);
assert.deepEqual(annotation.graph, envelope.graph);
assert.equal(annotation.graph.total_macs, 786560);
const multiFile = structuredClone(envelope);
multiFile.external_files = [{ path: "weights.bin", sha256: "b".repeat(64), byte_length: 32 }];
delete multiFile.envelope_sha256;
multiFile.envelope_sha256 = createHash("sha256").update(canonicalJson(multiFile)).digest("hex");
const bound = buildSpdxArtifactDocument(multiFile, options);
assertSpdx23(bound);
assert.equal(bound.packages.length, 2);
assert.equal(bound.relationships[0].relatedSpdxElement, bound.packages[1].SPDXID);
assert.notEqual(bound.documentNamespace, document.documentNamespace);
const tampered = structuredClone(envelope);
tampered.identity.sha256 = "f".repeat(64);
assert.throws(() => buildSpdxArtifactDocument(tampered, options), /valid evidence envelope/);
assert.throws(() => buildSpdxArtifactDocument(buildArtifactEvidenceEnvelope(analysis), options), /artifact SHA-256/);
console.log("SPDX 2.3 artifact export passed (pinned official schema, file-purpose package identities, measured hashes, evidence annotations, explicit license unknowns, dependencies, tamper rejection).");
