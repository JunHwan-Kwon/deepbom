import { readFile, writeFile } from "node:fs/promises";
import { parse } from "acorn";

const sourcePath = "web/lib/report-findings.js";
const outputPath = "web/lib/finding-rule-catalog.generated.js";
const source = await readFile(sourcePath, "utf8");
const tree = parse(source, { ecmaVersion: "latest", sourceType: "module", locations: true });
const records = new Map();

walk(tree, []);
const sorted = [...records.values()].sort((a, b) => a.finding_id.localeCompare(b.finding_id));
if (sorted.length !== 119) throw new Error(`Expected 119 canonical finding rules, observed ${sorted.length}.`);
const moduleSource = `// Generated by scripts/generate-finding-rule-catalog.mjs. Do not edit directly.\nexport const GENERATED_FINDING_RULES = Object.freeze(${JSON.stringify(Object.fromEntries(sorted.map((row) => [row.finding_id, row])), null, 2)});\n`;
if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8");
  if (current !== moduleSource) throw new Error(`${outputPath} is stale; run npm run generate:finding-rule-catalog.`);
  console.log(`Finding-rule catalog is synchronized (${sorted.length} rules).`);
} else {
  await writeFile(outputPath, moduleSource, "utf8");
  console.log(`Generated ${outputPath} (${sorted.length} rules).`);
}

function walk(node, conditions) {
  if (!node || typeof node !== "object") return;
  if (node.type === "CallExpression" && node.callee?.type === "Identifier" && node.callee.name === "finding") {
    collectArgument(node.arguments[0], conditions, node.loc?.start?.line || 0);
    return;
  }
  if (node.type === "IfStatement") {
    walk(node.test, conditions);
    const test = expression(node.test);
    walk(node.consequent, [...conditions, test]);
    if (node.alternate) walk(node.alternate, [...conditions, `not (${test})`]);
    return;
  }
  if (node.type === "ConditionalExpression") {
    walk(node.test, conditions);
    const test = expression(node.test);
    walk(node.consequent, [...conditions, test]);
    walk(node.alternate, [...conditions, `not (${test})`]);
    return;
  }
  for (const [key, value] of Object.entries(node)) {
    if (["start", "end", "loc"].includes(key)) continue;
    if (Array.isArray(value)) value.forEach((item) => walk(item, conditions));
    else if (value?.type) walk(value, conditions);
  }
}

function collectArgument(node, conditions, fallbackLine) {
  if (node?.type === "ConditionalExpression") {
    const test = expression(node.test);
    collectArgument(node.consequent, [...conditions, test], fallbackLine);
    collectArgument(node.alternate, [...conditions, `not (${test})`], fallbackLine);
    return;
  }
  if (node?.type !== "ObjectExpression") throw new Error(`finding() at line ${fallbackLine} must use a static object or conditional branches.`);
  const id = requiredStatic(node, "id", fallbackLine);
  const titleVariants = staticStrings(property(node, "title"));
  if (!titleVariants.length) throw new Error(`finding() title at line ${fallbackLine} must have static conditional branches.`);
  const title = titleVariants.length === 1 ? titleVariants[0] : `${id} conditional evidence status`;
  const categoryVariants = staticStrings(property(node, "category"));
  if (!categoryVariants.length) throw new Error(`finding() category at line ${fallbackLine} must have static conditional branches.`);
  const category = categoryVariants.length === 1 ? categoryVariants[0] : "conditional";
  const evidenceVariants = staticStrings(property(node, "evidence"));
  const evidence = evidenceVariants.length === 1 ? evidenceVariants[0] : expression(property(node, "evidence"));
  const explicitKinds = staticStrings(property(node, "findingKind"));
  const possibleKinds = explicitKinds.length
    ? explicitKinds
    : [...new Set(categoryVariants.flatMap((categoryValue) => (evidenceVariants.length ? evidenceVariants : [evidence]).map((evidenceValue) => inferredKind(categoryValue, evidenceValue))))];
  const recommendation = staticValue(property(node, "recommendation"));
  const relevance = staticValue(property(node, "relevance"));
  const priority = staticValue(property(node, "priority")) || expression(property(node, "priority"));
  const record = {
    finding_id: id,
    title,
    ...(titleVariants.length > 1 ? { title_variants: titleVariants } : {}),
    category,
    ...(categoryVariants.length > 1 ? { category_variants: categoryVariants } : {}),
    applicable_formats: formatsFor(id),
    finding_kind: possibleKinds.length === 1 ? possibleKinds[0] : "conditional",
    possible_finding_kinds: possibleKinds,
    default_priority_basis: priority || "computed by the canonical report branch",
    evidence_requirements: evidencePointers(id),
    trigger_contract: conditions.length ? conditions.slice(-3).join(" AND ") : "The canonical report synthesis reaches this unconditional evidence-boundary finding.",
    false_positive_boundary: falsePositiveBoundary(category, evidence),
    remediation: recommendation || "Review the emitted observation and interpretation, then bind the missing artifact, source, build, or runtime evidence named by the finding.",
    method_reference: `deepbom.report_findings.${id}.v1`,
    source_reference: { path: sourcePath, line: node.loc?.start?.line || fallbackLine },
    evidence_class_basis: evidence || "computed by the canonical report branch",
    relevance: relevance || "engineering evidence review",
  };
  const prior = records.get(id);
  if (!prior) {
    records.set(id, record);
    return;
  }
  const triggerContracts = [...new Set([...(prior.trigger_contracts || [prior.trigger_contract]), record.trigger_contract])];
  const mergedTitles = [...new Set([...(prior.title_variants || [prior.title]), ...(record.title_variants || [record.title])])];
  const mergedCategories = [...new Set([...(prior.category_variants || [prior.category]), ...(record.category_variants || [record.category])])];
  const mergedKinds = [...new Set([...(prior.possible_finding_kinds || [prior.finding_kind]), ...(record.possible_finding_kinds || [record.finding_kind])])];
  records.set(id, {
    ...prior,
    title: mergedTitles.length === 1 ? mergedTitles[0] : `${id} conditional evidence status`,
    title_variants: mergedTitles,
    category: mergedCategories.length === 1 ? mergedCategories[0] : "conditional",
    category_variants: mergedCategories,
    finding_kind: mergedKinds.length === 1 ? mergedKinds[0] : "conditional",
    possible_finding_kinds: mergedKinds,
    default_priority_basis: mergeText(prior.default_priority_basis, record.default_priority_basis),
    evidence_requirements: [...new Set([...prior.evidence_requirements, ...record.evidence_requirements])],
    trigger_contract: triggerContracts.map((value) => `(${value})`).join(" OR "),
    trigger_contracts: triggerContracts,
    remediation: mergeText(prior.remediation, record.remediation),
    source_reference: {
      path: sourcePath,
      lines: [...new Set([...(prior.source_reference.lines || [prior.source_reference.line]), record.source_reference.line])],
    },
    evidence_class_basis: mergeText(prior.evidence_class_basis, record.evidence_class_basis),
  });
}

function property(object, name) {
  return object?.properties?.find((item) => item.type === "Property" && !item.computed && (item.key.name || item.key.value) === name)?.value || null;
}

function requiredStatic(object, name, line) {
  const value = staticValue(property(object, name));
  if (!value) throw new Error(`finding() ${name} at line ${line} must be a non-empty static string.`);
  return value;
}

function staticValue(node) {
  if (node?.type === "Literal" && typeof node.value === "string") return node.value;
  if (node?.type === "TemplateLiteral" && node.expressions.length === 0) return node.quasis[0].value.cooked;
  return "";
}

function staticStrings(node) {
  if (node?.type === "ConditionalExpression") return [...new Set([...staticStrings(node.consequent), ...staticStrings(node.alternate)])];
  const value = staticValue(node);
  return value ? [value] : [];
}

function expression(node) {
  if (!node || !Number.isInteger(node.start) || !Number.isInteger(node.end)) return "";
  const value = source.slice(node.start, node.end).replace(/\s+/g, " ").trim();
  return value.length <= 360 ? value : `${value.slice(0, 357)}...`;
}

function evidencePointers(id) {
  const pattern = new RegExp(`"${id}"\\s*:\\s*\\[([^\\]]*)\\]`);
  const match = pattern.exec(source);
  const values = match ? [...match[1].matchAll(/"([^"]+)"/g)].map((item) => item[1]) : [];
  return values.length ? values : ["/evidence/findings_register/findings"];
}

function formatsFor(id) {
  const family = id.split("-")[1];
  const map = {
    CML: ["coreml"], ONX: ["onnx"], SER: ["gguf", "safetensors"], DEL: ["tflite"],
    PKG: ["tflite"], CHN: ["tflite"], QNT: ["tflite", "onnx"], WGT: ["tflite", "onnx"],
    DYN: ["tflite", "onnx"], MEM: ["tflite", "onnx"], SYN: ["tflite"],
    IOC: ["tflite", "onnx", "coreml", "executorch"], OUT: ["tflite", "onnx", "coreml", "executorch"],
    GRF: ["tflite", "onnx", "coreml", "executorch"],
  };
  return map[family] || ["all"];
}

function inferredKind(category, evidence) {
  const normalizedEvidence = String(evidence || "").toUpperCase();
  if (["NOT_ASSESSABLE", "DECLARED_UNVERIFIED"].includes(normalizedEvidence)) return "evidence_gap";
  if (["lineage", "limitation", "evidence_completeness", "evidence_reproducibility"].includes(category)) return "evidence_gap";
  if (["integrity", "numerical_integrity", "input_contract", "output_contract", "integration_verification"].includes(category)
    && ["OBSERVED", "DERIVED", "OBSERVED/DERIVED", "SOURCE_PINNED_AND_OBSERVED"].includes(normalizedEvidence)) return "artifact_defect";
  return "caution";
}

function falsePositiveBoundary(category, evidence) {
  if (String(evidence).includes("NOT_ASSESSABLE") || ["lineage", "limitation", "evidence_completeness"].includes(category)) {
    return "This is an evidence gap, not evidence that the artifact or deployed system is defective.";
  }
  if (["quantization_design_review", "quantization_calibration_review", "memory_cache", "packing", "channel_alignment", "runtime"].includes(category)) {
    return "The static or heuristic trigger is a review signal; runtime behavior and task impact require separately identified evidence.";
  }
  return "The finding is bounded to the serialized facts and deterministic checks named in evidence_requirements; it does not establish task, clinical, or runtime impact beyond that boundary.";
}

function mergeText(left, right) {
  return left === right ? left : [...new Set([left, right])].join(" OR ");
}
